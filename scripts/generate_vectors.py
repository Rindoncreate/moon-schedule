"""Independent recurrence oracle; never imports the MoonBit implementation.

Requires python-dateutil==2.9.0.post0 for reproducible fixtures. Stdlib datetime
is the separate calendar arithmetic oracle. Production has no Python dependency.
"""
from __future__ import annotations

import argparse
import json
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path

import dateutil
from dateutil.rrule import rrulestr

ROOT = Path(__file__).resolve().parents[1]
SEED = 55452026


def stamp(value: datetime) -> str:
    return f"{value.year:04}-{value.month:02}-{value.day:02}T{value.hour:02}:{value.minute:02}Z"


def date(text: str) -> datetime:
    return datetime.strptime(text, "%Y-%m-%dT%H:%MZ").replace(tzinfo=timezone.utc)


def recurrence_inputs() -> list[dict]:
    curated = [
        ("FREQ=MONTHLY;COUNT=5", "2024-01-31T09:00Z"),
        ("FREQ=YEARLY;COUNT=3", "2024-02-29T09:00Z"),
        ("FREQ=WEEKLY;BYDAY=MO,WE,FR;COUNT=9", "2025-01-06T09:00Z"),
        ("FREQ=WEEKLY;INTERVAL=2;BYDAY=TU,SU;WKST=MO;COUNT=8", "1997-08-05T09:00Z"),
        ("FREQ=WEEKLY;INTERVAL=2;BYDAY=TU,SU;WKST=SU;COUNT=8", "1997-08-05T09:00Z"),
        ("FREQ=MONTHLY;BYMONTHDAY=1,15;COUNT=8", "2025-01-01T09:00Z"),
        ("FREQ=MONTHLY;BYMONTHDAY=-1;COUNT=8", "2024-01-31T09:00Z"),
        ("FREQ=MONTHLY;BYDAY=1MO,-1FR;COUNT=8", "2025-01-06T09:00Z"),
        ("FREQ=MONTHLY;BYDAY=MO;BYSETPOS=1;COUNT=8", "2025-01-13T09:00Z"),
        ("FREQ=MONTHLY;BYDAY=MO,TU,WE,TH,FR;BYSETPOS=-1;COUNT=8", "2025-01-31T09:00Z"),
        ("FREQ=YEARLY;BYMONTH=1,3;COUNT=8", "2025-01-10T09:00Z"),
        ("FREQ=YEARLY;BYDAY=-1MO;COUNT=4", "2024-12-30T09:00Z"),
        ("FREQ=YEARLY;BYMONTH=1,2;BYDAY=1MO;COUNT=8", "2025-01-06T09:00Z"),
        ("FREQ=YEARLY;BYMONTHDAY=1,-1;BYSETPOS=1,-1;COUNT=8", "2024-01-01T09:00Z"),
        ("FREQ=DAILY;UNTIL=20250103T090000Z", "2025-01-01T09:00Z"),
        ("FREQ=DAILY;INTERVAL=2147483647;COUNT=1", "2025-01-01T09:00Z"),
    ]
    inputs = []
    for rule, start in curated:
        anchor = date(start)
        # Leap-day yearly examples need more than eight years of query horizon.
        end = anchor + timedelta(days=366 * 10)
        inputs.append({"rule": rule, "start": start, "from": start, "end": stamp(end)})

    rng = random.Random(SEED)
    days = ["MO", "TU", "WE", "TH", "FR", "SA", "SU"]
    for _ in range(144):
        year = rng.choice([1899, 1900, 1997, 1999, 2000, 2024, 2025, 2099, 2100])
        anchor = datetime(year, rng.randint(1, 12), rng.randint(1, 28), rng.randint(0, 23), rng.choice([0, 15, 30, 59]), tzinfo=timezone.utc)
        freq = rng.choice(["DAILY", "WEEKLY", "MONTHLY", "YEARLY"])
        parts = [f"FREQ={freq}", f"INTERVAL={rng.choice([1, 2, 3])}"]
        has_by = False
        if rng.randrange(3):
            selected = rng.sample(days, rng.randint(1, 3))
            if freq in ["MONTHLY", "YEARLY"] and rng.randrange(2):
                selected = [f"{rng.choice([1, 2, -1, -2])}{item}" for item in selected]
            parts.append("BYDAY=" + ",".join(selected))
            has_by = True
        if freq != "WEEKLY" and rng.randrange(3) == 0:
            parts.append("BYMONTHDAY=" + ",".join(str(n) for n in rng.sample([1, 2, 15, 28, 29, 30, 31, -1, -2], rng.randint(1, 3))))
            has_by = True
        if rng.randrange(3) == 0:
            parts.append("BYMONTH=" + ",".join(str(n) for n in rng.sample(range(1, 13), rng.randint(1, 3))))
            has_by = True
        if freq == "WEEKLY":
            parts.append("WKST=" + rng.choice(days))
        if has_by and rng.randrange(3) == 0:
            parts.append("BYSETPOS=" + rng.choice(["1", "-1", "2,-1", "1,-1"]))
        if rng.randrange(2):
            parts.append(f"COUNT={rng.randint(1, 12)}")
        else:
            parts.append("UNTIL=" + (anchor + timedelta(days=900)).strftime("%Y%m%dT%H%M00Z"))
        lower = anchor + timedelta(days=rng.choice([0, 1, 30, 365]))
        inputs.append({"rule": ";".join(parts), "start": stamp(anchor), "from": stamp(lower), "end": stamp(anchor + timedelta(days=950))})
    return inputs


def generate() -> tuple[str, str]:
    if dateutil.__version__ != "2.9.0.post0":
        raise RuntimeError("Fixture generation requires python-dateutil==2.9.0.post0")
    fixtures = []
    source = [
        "// Generated by scripts/generate_vectors.py with python-dateutil 2.9.0.post0.",
        "// Independent reference outputs, not computed by MoonSchedule. Do not edit.",
        "",
    ]
    for i, case in enumerate(recurrence_inputs()):
        start, lower, upper = (date(case[k]) for k in ["start", "from", "end"])
        reference = rrulestr(case["rule"], dtstart=start)
        expected = [stamp(value) for value in reference.between(lower, upper, inc=True)]
        fixtures.append({"id": i, **case, "expected": expected})
        q = lambda key: json.dumps(case[key])
        source += [
            "///|", f'test "dateutil oracle recurrence {i:03}" {{',
            f'  let rule = @schedule.RRule::parse({q("rule")})',
            "  let actual = rule.occurrences_window(",
            f'    @schedule.DateTime::parse({q("start")}),',
            f'    @schedule.DateTime::parse({q("from")}),',
            f'    @schedule.DateTime::parse({q("end")}),',
            "  ).map(value => value.to_string())",
            "  let expected : Array[String] = [",
            *[f"    {json.dumps(value)}," for value in expected],
            "  ]", "  assert_eq(actual, expected)",
            "  if expected.length() > 0 {",
            "    let next = rule.next_after_from(",
            f'      @schedule.DateTime::parse({q("start")}),',
            f'      @schedule.DateTime::parse({q("from")}).add_minutes(-1),',
            "    )",
            "    assert_eq(next.map(value => value.to_string()), Some(expected[0]))",
            "  }", "}", "",
        ]
    rng = random.Random(SEED + 1)
    calendar = []
    for i in range(40):
        start = datetime(rng.randint(2000, 4000), rng.randint(1, 12), rng.randint(1, 28), rng.randint(0, 23), rng.randint(0, 59), tzinfo=timezone.utc)
        delta = rng.randint(-1000000000, 1000000000)
        expected = stamp(start + timedelta(minutes=delta))
        calendar.append({"start": stamp(start), "minutes": delta, "expected": expected})
        source += ["///|", f'test "stdlib datetime oracle arithmetic {i:03}" {{',
                   f'  let date = @schedule.DateTime::parse({json.dumps(stamp(start))})',
                   f'  assert_eq(date.add_minutes({delta}).to_string(), {json.dumps(expected)})', "}", ""]
    manifest = {"oracle": "python-dateutil==2.9.0.post0 + Python stdlib datetime", "seed": SEED, "recurrence": fixtures, "calendar": calendar}
    return json.dumps(manifest, indent=2) + "\n", "\n".join(source)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Verify JSON fixture bytes without writing anything")
    args = parser.parse_args()
    manifest, source = generate()
    fixture = ROOT / "fixtures" / "reference-vectors.json"
    if args.check:
        if fixture.read_text(encoding="utf-8") != manifest:
            raise SystemExit("Reference fixtures differ from the pinned independent oracle")
        print("Independent oracle: 160 recurrence + 40 calendar vectors verified")
    else:
        fixture.parent.mkdir(parents=True, exist_ok=True)
        fixture.write_text(manifest, encoding="utf-8", newline="\n")
        (ROOT / "reference_vectors_test.mbt").write_text(source, encoding="utf-8", newline="\n")
        print("Generated 200 independent reference tests; run moon fmt then moon test")


if __name__ == "__main__":
    main()
